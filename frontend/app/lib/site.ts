import type { Metadata } from "next";

/** The live site. Only this origin may be indexed. */
export const PRODUCTION_URL = "https://souvenote.com";

/**
 * This deployment's origin, used for canonical URLs, the sitemap and robots.txt.
 * Staging and preview deploys set NEXT_PUBLIC_SITE_URL to their own address, so
 * their canonicals point at themselves and they stay out of search (audit E7).
 */
export const SITE_URL = (process.env.NEXT_PUBLIC_SITE_URL || PRODUCTION_URL).replace(/\/+$/, "");

/**
 * Search engines may index this deployment only when it is the live site, and
 * NEXT_PUBLIC_ALLOW_INDEXING isn't "false". Anywhere else robots.txt disallows
 * everything and every response carries X-Robots-Tag: noindex (next.config.mjs).
 */
export const SITE_INDEXABLE = SITE_URL === PRODUCTION_URL && process.env.NEXT_PUBLIC_ALLOW_INDEXING !== "false";

export const SITE_NAME = "Souvenote";

/** Default description (matches the landing page) for routes without their own. */
export const SITE_DESCRIPTION =
  "Create personalized greeting cards with AI-designed artwork and an optional original song linked by QR code. Printed and delivered to their door.";

/**
 * The site-wide share image: a static 1200x630 JPEG, app/opengraph-image.jpg (about
 * 100 kB; audit E10). It used to be generated by app/opengraph-image.tsx as an 850 kB
 * PNG; that file is kept, retired, in asset-originals/opengraph-image.tsx.retired.
 */
export const SHARE_IMAGE = {
  url: "/opengraph-image.jpg",
  width: 1200,
  height: 630,
  alt: "Souvenote: a comic-book style card cover starring a smiling mom as a superhero",
};

/**
 * Open Graph block for a page. Page-level `openGraph` replaces the inherited
 * one entirely (including the share image, app/opengraph-image.jpg), so
 * the shared fields and the image are set explicitly here.
 */
export function openGraphFor(path: string, title: string, description: string): Metadata["openGraph"] {
  return {
    title,
    description,
    url: path,
    siteName: SITE_NAME,
    type: "website",
    locale: "en_CA",
    images: [SHARE_IMAGE],
  };
}

/** For auth utility screens: keep them out of search and AI answers, but let crawlers follow their links. */
export const NOINDEX: Metadata["robots"] = { index: false, follow: true };
